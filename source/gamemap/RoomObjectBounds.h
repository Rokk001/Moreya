//! Names of the dungeon heart meshes, one per health tier (see RoomDungeonTemple.cpp).
//! They have to match the entries of meshBounds.
static const std::string HEART_MESH_HEALTHY = "DungeonHeartObjectHealthy";
static const std::string HEART_MESH_DAMAGED = "DungeonHeartObjectDamaged";
static const std::string HEART_MESH_CRITICAL = "DungeonHeartObjectCritical";

//! Returns true if name is the mesh of the dungeon heart in any health tier.
inline bool isDungeonHeartMesh(const std::string& name)
{
    return name == HEART_MESH_HEALTHY || name == HEART_MESH_DAMAGED || name == HEART_MESH_CRITICAL;
}

//! Names of the Moreya gate models (see RoomPortalWave.cpp): the arch and its portcullis. They have to match the
//! entries of meshBounds. The arch is walked through; the portcullis blocks the passage while the gate is closed and
//! is sunk below the floor while it is open.
static const std::string MOREYA_GATE_MESH = "MoreyaGate";
static const std::string MOREYA_PORTCULLIS_MESH = "MoreyaGatePortcullis";

//! \brief Returns true if name is the arch or the portcullis of the Moreya gate.
inline bool isMoreyaGateMesh(const std::string& name)
{
    return name == MOREYA_GATE_MESH || name == MOREYA_PORTCULLIS_MESH;
}

//! Names of the pool pieces of the lava spa. Creatures walk over them (the mud only hides the lower body), so they are
//! no obstacles; they have to match the entries of meshBounds.
static const std::string SPA_POOL_MESH = "SpaMudPool";
static const std::string SPA_RIM_MESH = "SpaPoolRim";

//! Returns true if name is a walkable piece of the lava spa pool (the mud or its rim).
inline bool isWalkableSpaMesh(const std::string& name)
{
    return name == SPA_POOL_MESH || name == SPA_RIM_MESH;
}

//! Name of the seat of a toilet room (see RoomToilet.cpp). It has to match the entry of meshBounds. The seat is solid:
//! only its user steps onto it (RoomToilet walks the user there on a checked straight line).
static const std::string TOILET_SEAT_MESH = "ToiletSeat";
//! Height of the stone top of the toilet seat; a creature that uses the seat is drawn this much higher.
constexpr float toiletSeatTop = 0.18f;
//! Where on the seat its user is placed: mesh coordinate y (the back of the seat, at the wall, is at +y). The hole lies
//! just behind it, so the feet of the user stand on the stone in front of and beside the hole.
constexpr float toiletSeatPlaceY = 0.17f;

//! \brief True when the point (world x, y) lies on the top of a toilet seat placed at seatX, seatY with the given angle
//! (degrees), i.e. inside its measured footprint.
inline bool onToiletSeat(float pointX, float pointY, float seatX, float seatY, float angleDegrees)
{
    const float angle = angleDegrees * degreesToRadians;
    const float dx = pointX - seatX;
    const float dy = pointY - seatY;
    // Back into the mesh coordinates of the seat (rotation by -angle)
    const float localX = dx * std::cos(angle) + dy * std::sin(angle);
    const float localY = -dx * std::sin(angle) + dy * std::cos(angle);
    for(const MeshBounds& bounds : meshBounds)
    {
        if(TOILET_SEAT_MESH != bounds.name)
            continue;
        return localX >= bounds.minX && localX <= bounds.maxX && localY >= bounds.minY && localY <= bounds.maxY;
    }
    return false;
}

// Narrow the visible furniture and its navigation bounds together. Leave Z
// unchanged so authored working heights and bed support surfaces stay valid.
// Large beds keep their existing multi-tile allocation; this is not a capacity
// or placement rule. Already compact meshes are never enlarged.
struct FurnitureScale
{
    float x, y;
};

// Footprint (in tiles) that furniture is narrowed to. Beds that are not assigned
// to a creature use the smaller one, large beds the larger one.
constexpr float furnitureFootprint = 0.6f;
constexpr float unassignedBedFootprint = 0.4f;
constexpr float largeBedFootprint = 1.2f;
// Longest diagonal (in tiles) of a treasury pile.
constexpr float treasuryPileDiagonal = 0.4f;

// Returns how much the mesh is narrowed so that it fits the footprint of its kind.
//! \brief Keeps cots at their authored footprint and narrows other furniture as required.
//! \brief Matches renderer and navigation scales while preserving authored equipment-room furniture sizes.
//! The tavern counter is narrowed across to exactly its own tile, so it never reaches off the room (INGAME-QS-11 K9).
inline FurnitureScale furnitureScale(const MeshBounds& bounds)
{
    const std::string name(bounds.name);
    if(name.compare(0, 12, "InfirmaryCot") == 0)
        return {1.0f, 1.0f};
    // The counter mesh is 1.04 tiles wide (x -0.52 to 0.52); narrowed to 1.0 it ends at the edges of its tile, and its
    // depth stays as authored
    if(name == "TavernCounter")
        return {1.0f / (bounds.maxX - bounds.minX), 1.0f};
    if(name == "FenceCorner" || name == "FenceStraight" || name == "PrisonDoor" ||
       name == "PortalObject" || isMoreyaGateMesh(name) || isDungeonHeartMesh(name) ||
       name == "SalesTable" || name == "MerchantShelf" || name == "Cauldron" ||
       name == "HerbBed" || name == "StillShelf" || name == "WaterTrough" ||
       name == "MushroomLamp" || name == "ItemBag" || name == "GhostCauldron" || name == "ManaStill" || name == "GhostPress" ||
       name == "SoulForge" ||
       name == "SpaChair" || name == "SpaMudPool" || name == "SpaPoolRim" || name == "SpaSpringboard" ||
       name == "TavernKeg" || name == "TavernStool" || name == "TavernTable" ||
       name == TOILET_SEAT_MESH)
        return {1.0f, 1.0f};
    // Treasury piles can fill adjacent tiles at arbitrary angles. Bound their
    // diagonal, not just their unrotated width, so rotation retains the margin.
    if(name.compare(0, 9, "Goldstack") == 0)
    {
        const float scale = std::min(1.0f, treasuryPileDiagonal / std::hypot(
            bounds.maxX - bounds.minX, bounds.maxY - bounds.minY));
        return {scale, scale};
    }
    float width = furnitureFootprint, depth = furnitureFootprint;
    const bool bed = name == "Bed" || name == "KnightCoffin" || name == "StoneCoffin" ||
        (name.size() >= 3 && name.compare(name.size() - 3, 3, "Bed") == 0);
    // This fallback also covers unassigned decorative instances. Actual beds
    // override it with the owning creature's allocated dimensions below.
    if(bed)
        width = depth = unassignedBedFootprint;
    if(name == "DragonBed" || name == "TrollBed")
        width = depth = largeBedFootprint;
    else if(name == "Bed" || name == "KnightCoffin" || name == "LizardmanBed" ||
            name == "OrcBed" || name == "RangerBed" || name == "StoneCoffin")
        depth = largeBedFootprint;
    const float x = std::min(1.0f, width / (bounds.maxX - bounds.minX));
    const float y = std::min(1.0f, depth / (bounds.maxY - bounds.minY));
    if(bed)
        return {x, y};
    const float scale = std::min(x, y);
    return {scale, scale};
}

// Only beds and cots are low enough to be stepped onto (decision 710: a wide creature, the Troll, climbed onto the ghost
// room apparatuses and stood at wall height; decision 727: the coffins of the crypt are graves, nobody sleeps in them,
// and a creature that climbed onto one walked over the grave). Every other object, measured or not, is a solid obstacle.
inline bool isSteppableMesh(const std::string& name)
{
    return name == "Bed" ||
        (name.size() >= 3 && name.compare(name.size() - 3, 3, "Bed") == 0) ||
        (name.compare(0, 12, "InfirmaryCot") == 0);
}

// A bed covers this fraction of its tile width and depth; the rest is the lane
// between two neighbouring beds. A creature wider than that lane cannot use it.
constexpr float bedTileFill = 0.70f;
constexpr float bedLaneWidth = 1.0f - bedTileFill;

// Position of the mesh origin, angle in degrees and scale of a bed.
struct BedPlacement
{
    float x, y, angle;
    FurnitureScale scale;
};

// FNV-1a hash parameters, used to derive a stable angle from the creature name.
constexpr std::uint32_t bedHashBasis = 2166136261u;
constexpr std::uint32_t bedHashPrime = 16777619u;
// The angle of a bed differs from the allocated angle by up to bedAngleJitter degrees,
// in bedAngleSteps equal steps.
constexpr std::uint32_t bedAngleSteps = 8001u;
constexpr float bedAngleStep = 0.001f;
constexpr float bedAngleJitter = 4.0f;
// Start values for the search of the corner of the rotated bed.
constexpr float bedCornerSentinel = 1.0e10f;

// Returns where a bed for the given creature is placed in the allocated area of
// width x height tiles whose lower left tile is (x, y); the angle is the allocated one.
inline BedPlacement bedPlacement(const MeshBounds& bounds, int x, int y,
    int width, int height, float allocationAngle, const std::string& creatureName)
{
    // Stable across save/load and platforms, without consuming gameplay RNG.
    std::uint32_t hash = bedHashBasis;
    for(unsigned char character : creatureName)
        hash = (hash ^ character) * bedHashPrime;
    const float angle = allocationAngle + float(hash % bedAngleSteps) * bedAngleStep - bedAngleJitter;
    const float radians = angle * degreesToRadians;
    const float cosine = std::cos(radians), sine = std::sin(radians);
    // Fit the rotated footprint, keeping the right and bottom 30% lanes clear.
    const float c = std::abs(cosine), s = std::abs(sine);
    const float determinant = c * c - s * s;
    const FurnitureScale scale{bedTileFill * (width * c - height * s) /
            (determinant * (bounds.maxX - bounds.minX)),
        bedTileFill * (height * c - width * s) /
            (determinant * (bounds.maxY - bounds.minY))};
    float left = bedCornerSentinel, top = -bedCornerSentinel;
    for(float px : {bounds.minX * scale.x, bounds.maxX * scale.x})
        for(float py : {bounds.minY * scale.y, bounds.maxY * scale.y})
        {
            left = std::min(left, cosine * px - sine * py);
            top = std::max(top, sine * px + cosine * py);
        }
    return {float(x) - 0.5f - left, float(y + height) - 0.5f - top, angle, scale};
}

