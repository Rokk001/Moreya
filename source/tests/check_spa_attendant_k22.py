def skin_points(p, vertices):
    """Positions of vertices in a pose (linear blend skinning)."""
    out = np.zeros((len(vertices), 3))
    for k, v in enumerate(vertices):
        point = np.append(positions[v], 1)
        out[k] = sum(w * (p[bone] @ INVERSE_BIND[bone] @ point)[:3] for bone, w in weights[v].items())
    return out


